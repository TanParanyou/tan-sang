/**
 * Returns a randomly picked dish from RANDOM_DISHES.
 * If excludeNameTh is provided and there are other choices available,
 * it will avoid picking the same dish name consecutively.
 */
export function getRandomDish(excludeNameTh?: string): RandomDishItem {
  if (RANDOM_DISHES.length === 0) {
    return { nameTh: 'ข้าวกะเพราหมูสับ', nameEn: 'Stir-fried Basil Minced Pork with Rice' };
  }

  const pool = excludeNameTh
    ? RANDOM_DISHES.filter((dish) => dish.nameTh !== excludeNameTh)
    : RANDOM_DISHES;

  const candidatePool = pool.length > 0 ? pool : RANDOM_DISHES;
  const randomIndex = Math.floor(Math.random() * candidatePool.length);
  const picked = candidatePool[randomIndex];
  return picked ?? { nameTh: 'ข้าวกะเพราหมูสับ', nameEn: 'Stir-fried Basil Minced Pork with Rice' };
}
